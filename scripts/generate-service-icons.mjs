#!/usr/bin/env node
// Freeze the brand marks we show into a source file: scripts/generate-service-icons.mjs
//
// Why generate instead of importing at runtime:
//
//   * No network at display time. A logo CDN (logo.dev, Composio's asset host, anything else)
//     would mean the panel makes a request per service the user has connected — telling a third
//     party which integrations they use, every time they open Settings. For a product whose whole
//     claim is that your data stays on the device, that is the wrong trade for an icon.
//   * No runtime dependency. simple-icons is ~3000 icons behind a barrel file; importing from it
//     leaves the bundle at the mercy of tree-shaking. Seven paths in a generated file is bytes.
//   * It keeps working offline, forever, at the version we checked.
//
// simple-icons is CC0-1.0 (public domain). Marks the project has removed on trademark request
// (Slack, OpenAI) are absent on purpose — the UI falls back to a lettered disc for those rather
// than shipping an approximation.
//
//   pnpm --filter @shogun-ai/desktop exec node ../../scripts/generate-service-icons.mjs

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

// Resolve from the desktop package: that is where simple-icons is a devDependency, and this script
// lives at the repo root where pnpm has linked nothing.
const require = createRequire(new URL("../apps/desktop/package.json", import.meta.url));
const si = require("simple-icons");

/** Our service/provider id → the simple-icons export that carries its mark. */
const WANTED = [
  ["gmail", "siGmail"],
  ["gcal", "siGooglecalendar"],
  ["gdrive", "siGoogledrive"],
  ["notion", "siNotion"],
  ["github", "siGithub"],
  ["linear", "siLinear"],
  // LLM providers, shown on the key/provider picker.
  ["anthropic", "siAnthropic"],
  ["gemini", "siGooglegemini"],
  ["openrouter", "siOpenrouter"],
  // Absent from simple-icons (removed on trademark request), handled by the lettered fallback:
  //   slack, openai
];

const entries = [];
const missing = [];
for (const [id, key] of WANTED) {
  const icon = si[key];
  if (!icon) {
    missing.push(`${id} (${key})`);
    continue;
  }
  entries.push({ id, title: icon.title, hex: icon.hex, path: icon.path });
}

if (missing.length) {
  console.error(`simple-icons no longer carries: ${missing.join(", ")}`);
  console.error("Update WANTED, or let the lettered fallback cover them.");
  process.exitCode = 1;
}

const body = entries
  .map((e) => `  ${e.id}: { title: ${JSON.stringify(e.title)}, hex: "#${e.hex}", path: ${JSON.stringify(e.path)} },`)
  .join("\n");

const out = `// GENERATED by scripts/generate-service-icons.mjs — do not edit by hand.
//
// Brand marks for the services SHOGUN connects to, frozen at build time from simple-icons
// (CC0-1.0, public domain). Inlined rather than fetched: a logo CDN would tell a third party which
// integrations each user has connected, every time they open Settings.
//
// Services simple-icons has removed on trademark request (Slack, OpenAI) are deliberately absent —
// the UI shows a lettered disc for those instead of an approximated logo.
//
// Regenerate:  node scripts/generate-service-icons.mjs

export interface ServiceIcon {
  /** The vendor's own name for the mark. */
  title: string;
  /** Brand colour. Near-black marks are re-tinted at render time so they stay visible on dark. */
  hex: string;
  /** SVG path data, drawn in a 24x24 viewBox. */
  path: string;
}

export const SERVICE_ICONS: Record<string, ServiceIcon> = {
${body}
};
`;

const dest = new URL("../apps/desktop/src/serviceIcons.ts", import.meta.url);
writeFileSync(dest, out);
console.log(`wrote ${entries.length} marks to apps/desktop/src/serviceIcons.ts`);
